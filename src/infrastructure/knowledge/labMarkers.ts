export function formatLabMarkersForPrompt(): string {
  return LAB_MARKERS.map((m) => {
    const parts = [`- ${m.label} [${m.unit}]`];
    if (m.guideline) parts.push(`meta de diretriz: ${m.guideline.label} (${m.guideline.source})`);
    if (m.critical) {
      const c = [m.critical.low !== undefined ? `< ${m.critical.low}` : null, m.critical.high !== undefined ? `> ${m.critical.high}` : null]
        .filter(Boolean)
        .join(" ou ");
      parts.push(`ALERTA (orientar procurar atendimento): ${c}`);
    }
    if (m.notes) parts.push(`nota: ${m.notes}`);
    if (m.foodFocusLow) parts.push(`se baixo: ${m.foodFocusLow}`);
    if (m.foodFocusHigh) parts.push(`se alto: ${m.foodFocusHigh}`);
    return parts.join(" | ");
  }).join("\n");
}
